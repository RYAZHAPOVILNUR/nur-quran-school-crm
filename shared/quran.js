export function surahName(n) {
  const s = SURAHS[n - 1];
  return s ? s[1] : '';
}

// Страницы суры: от первой страницы до страницы перед следующей сурой (или той же, если следующая начинается на ней).
export function surahPages(n) {
  const start = SURAHS[n - 1][2];
  const end = n < 114 ? Math.max(start, SURAHS[n][2] - 1) : TOTAL_PAGES;
  return [start, end];
}

export function juzRange(j) {
  if (j === 1) return [1, 21];
  return [22 + (j - 2) * 20, j === 30 ? TOTAL_PAGES : 21 + (j - 1) * 20];
}

export function juzOfPage(p) {
  if (p <= 21) return 1;
  return Math.min(30, Math.floor((p - 22) / 20) + 2);
}

// Сура, с которой начинается страница (для подписи).
export function surahAtPage(p) {
  let found = 1;
  for (const [n, , start] of SURAHS) {
    if (start <= p) found = n; else break;
  }
  return found;
}

// Привычный порядок хифза в школе: 30-й джуз (с конца), 29-й, затем с начала мусхафа.
export const HIFZ_ORDER = (() => {
  const order = [];
  for (let p = 604; p >= 582; p--) order.push(p);
  for (let p = 581; p >= 562; p--) order.push(p);
  for (let p = 1; p <= 561; p++) order.push(p);
  return order;
})();

export function pagesLabel(from, to) {
  return from === to ? `стр. ${from}` : `стр. ${from}–${to}`;
}
